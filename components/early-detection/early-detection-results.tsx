"use client";

import React from "react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Brain, ShieldCheck, AlertTriangle, RefreshCcw, Info } from "lucide-react";

interface EarlyDetectionResultsProps {
  results: {
    predictedStatus: string;
    confidence: string;
    formData: any;
  } | null;
  error: string | null;
  loading: boolean;
  onReset: () => void;
}

export default function EarlyDetectionResults({
  results,
  error,
  loading,
  onReset,
}: EarlyDetectionResultsProps) {
  if (loading) {
    return (
      <Card className="h-full border-dashed border-2 flex items-center justify-center min-h-[400px]">
        <div className="text-center space-y-4">
          <RefreshCcw className="w-12 h-12 text-primary animate-spin mx-auto" />
          <p className="text-muted-foreground animate-pulse">Running advanced diagnostic models...</p>
        </div>
      </Card>
    );
  }

  if (error) {
    return (
      <Card className="h-full border-destructive/50 bg-destructive/5 flex items-center justify-center min-h-[400px]">
        <div className="text-center space-y-4 p-6">
          <AlertTriangle className="w-12 h-12 text-destructive mx-auto" />
          <h3 className="text-xl font-bold text-destructive">Prediction Error</h3>
          <p className="text-muted-foreground">{error}</p>
          <Button variant="outline" onClick={onReset}>Try Again</Button>
        </div>
      </Card>
    );
  }

  if (!results) {
    return (
      <Card className="h-full border-dashed border-2 flex items-center justify-center min-h-[400px] bg-muted/5">
        <div className="text-center space-y-4 p-8">
          <div className="w-16 h-16 bg-primary/10 rounded-full flex items-center justify-center mx-auto">
            <Brain className="w-8 h-8 text-primary/60" />
          </div>
          <h3 className="text-xl font-semibold text-foreground">Ready for Analysis</h3>
          <p className="text-muted-foreground max-w-xs mx-auto">
            Please complete the assessment form to generate an early detection prediction.
          </p>
        </div>
      </Card>
    );
  }

  const isHighRisk = results.predictedStatus.toLowerCase().includes("risk") || 
                     results.predictedStatus.toLowerCase().includes("positive");

  return (
    <div className="space-y-6">
      <Card className={`overflow-hidden border-2 transition-all ${isHighRisk ? 'border-destructive/30 bg-destructive/5' : 'border-green-500/30 bg-green-500/5'}`}>
        <CardHeader className="pb-2">
          <CardTitle className="text-sm font-medium uppercase tracking-wider text-muted-foreground">Prediction Result</CardTitle>
        </CardHeader>
        <CardContent className="space-y-6">
          <div className="flex items-center gap-4">
            <div className={`p-4 rounded-full ${isHighRisk ? 'bg-destructive/10' : 'bg-green-500/10'}`}>
              {isHighRisk ? <AlertTriangle className="w-8 h-8 text-destructive" /> : <ShieldCheck className="w-8 h-8 text-green-600" />}
            </div>
            <div>
              <h2 className={`text-3xl font-bold ${isHighRisk ? 'text-destructive' : 'text-green-700'}`}>
                {results.predictedStatus}
              </h2>
              <p className="text-muted-foreground flex items-center gap-2">
                <Info className="w-4 h-4" />
                Confidence: <span className="font-semibold text-foreground">{results.confidence}</span>
              </p>
            </div>
          </div>

          <div className="bg-background/50 rounded-lg p-4 border border-border/50">
            <p className="text-sm leading-relaxed italic text-muted-foreground">
              Note: This prediction is generated by an AI model and should be used for informational purposes only. Consult with a medical professional for clinical diagnosis.
            </p>
          </div>

          <Button variant="outline" className="w-full" onClick={onReset}>
            Perform New Assessment
          </Button>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="text-lg">Key Indicators Applied</CardTitle>
        </CardHeader>
        <CardContent className="grid grid-cols-2 gap-4 text-sm">
          <div className="flex justify-between border-b pb-1">
            <span className="text-muted-foreground">Cognitive Score</span>
            <span className="font-medium">{results.formData.ScoreCognitif}/30</span>
          </div>
          <div className="flex justify-between border-b pb-1">
            <span className="text-muted-foreground">Stability Score</span>
            <span className="font-medium">{results.formData.ScoreStabiliteEquilibre}/30</span>
          </div>
          <div className="flex justify-between border-b pb-1">
            <span className="text-muted-foreground">Age</span>
            <span className="font-medium">{results.formData.age}</span>
          </div>
          <div className="flex justify-between border-b pb-1">
            <span className="text-muted-foreground">Mobility Level</span>
            <span className="font-medium">{results.formData.NiveauMobilite}</span>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}
